/**
 * main.ts
 *
 * pas2ts: the game's Turbo Pascal to TypeScript.
 *
 *   node tools/pas2ts/main.ts <program.pas> <out dir> [--dir <unit dir>]... [--inc <include dir>]... [--no-check]
 *
 * Writes one module per unit, and index.ts: the data image (every typed constant's bytes), and run(), which runs
 * each unit's initialization and then the program.
 */
import * as fs from 'node:fs';
import * as path from 'node:path';
import { Compiler, CompileError, STATIC_BASE } from './parser.ts';
import { Gen } from './codegen.ts';

const argv = process.argv.slice(2);
const dirs: string[] = [];
const incs: string[] = [];
const pos: string[] = [];
const hookNames: string[] = [];
const tapNames: string[] = [];
/** Units the program does not use, translated with it for the page's own use. */
const extraUnits: string[] = [];
for (let i = 0; i < argv.length; i++) {
  if (argv[i] === '--dir') dirs.push(argv[++i]);
  else if (argv[i] === '--inc') incs.push(argv[++i]);
  else if (argv[i] === '--hook') hookNames.push(argv[++i].toLowerCase());
  else if (argv[i] === '--tap') tapNames.push(argv[++i].toLowerCase());
  else if (argv[i] === '--unit') extraUnits.push(argv[++i]);
  else pos.push(argv[i]);
}
const [program, outDir] = pos;
if (!program || !outDir) {
  console.error('usage: main.ts <program.pas> <out dir> [--dir d]... [--inc d]...');
  process.exit(2);
}

try {
  const c = new Compiler(dirs, incs, ['FPC', 'WEB']);
  const prog = c.loadFile(program);
  for (const u of extraUnits) c.loadUnit(u, 'the command line');
  const gen = new Gen(c);
  for (const h of hookNames) gen.hooks.add(h);
  for (const h of tapNames) gen.taps.add(h);
  const texts = new Map<string, string>();
  for (const u of c.order) texts.set(u.name, gen.genUnit(u));
  const isAsync = gen.solveAsync();
  fs.mkdirSync(outDir, { recursive: true });
  for (const f of fs.readdirSync(outDir)) if (f.endsWith('.ts')) fs.unlinkSync(path.join(outDir, f));
  let total = 0;
  for (const [name, text] of texts) {
    const out = Gen.finish(text, isAsync);
    total += out.length;
    fs.writeFileSync(path.join(outDir, name.toLowerCase() + '.ts'), out);
  }
  // the data image, trimmed of its trailing zeros
  let end = c.staticTop - STATIC_BASE;
  while (end > 0 && c.image[end - 1] === 0) end--;
  const b64 = Buffer.from(c.image.subarray(0, end)).toString('base64');
  const lines: string[] = [];
  lines.push('// Generated by web/tools/pas2ts. Do not edit.');
  lines.push('// @ts-nocheck');
  for (const u of c.order) lines.push(`import * as ${u.name}_ from './${u.name.toLowerCase()}';`);
  lines.push('');
  lines.push(`export const STATIC_BASE = ${STATIC_BASE};`);
  lines.push(`export const STATIC_TOP = ${c.staticTop};`);
  lines.push(`export const IMAGE = "${b64}";`);
  lines.push('');
  lines.push(`export const units = { ${c.order.map((u) => `${u.name}: ${u.name}_`).join(', ')} };`);
  lines.push('');
  lines.push('// the procedure table: what a procedure variable holds is an index into it');
  lines.push(`import { FT } from '../rt/sys';`);
  c.procTable.forEach((f, i) => lines.push(`FT[${i + 1}] = ${f.unit.name}_.${f.jsName};`));
  lines.push('');
  lines.push('/** Run every unit\'s initialization, then the program. */');
  lines.push('export async function run(): Promise<void> {');
  for (const u of c.order) if (u.init) lines.push(`  ${isAsync.has(u.init.id) ? 'await ' : ''}${u.name}_.$init();`);
  lines.push('}');
  fs.writeFileSync(path.join(outDir, 'index.ts'), lines.join('\n') + '\n');
  const nAsync = c.allFuncs.filter((f) => isAsync.has(f.id)).length;
  console.log(
    `pas2ts: ${prog.name}: ${c.order.length} units, ${c.allFuncs.length} routines (${nAsync} async), ` +
      `${c.staticTop - STATIC_BASE} bytes of data, ${(total / 1024) | 0} KB of TypeScript`,
  );
} catch (e) {
  if (e instanceof CompileError) {
    console.error('pas2ts: ' + e.message);
    process.exit(1);
  }
  throw e;
}
